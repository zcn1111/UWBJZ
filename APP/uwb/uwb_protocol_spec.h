#ifndef __UWB_PROTOCOL_SPEC_H
#define __UWB_PROTOCOL_SPEC_H

/*
================================================================================
                          1. TDMA周期时序图
================================================================================

时间轴 (600ms为一个周期)
+--------+-------+-------+-------+-----+--------+-------------------------+
| Beacon | Slot0 | Slot1 | Slot2 | ... | Slot49 |  下一周期Beacon          |
|  (基站) | (Tag1)| (Tag2)| (Tag3)|     | (Tag50)|                         |
+--------+-------+-------+-------+-----+--------+-------------------------+
0ms     12ms    24ms    36ms          588ms   600ms                      1200ms

================================================================================
                          2. 单次测距时序 (SS-TWR)
================================================================================

标签(Tag)                           基站(Anchor)
    |                                    |
    |  ---- POLL (tagId,里程,线名) ----> |  Tag发送POLL，记录t1
    |                                    |  基站接收POLL，记录t2
    |  <--- RESPONSE (t2,t3) ---------- |  基站发送RESPONSE
    |                                    |  Tag接收RESPONSE，记录t4
    |  ---- FINAL (t1,t4) ------------> |  Tag发送FINAL
    |                                    |  基站接收FINAL，记录t6
    |                                    |  基站计算距离
    |                                    |

================================================================================
                          3. 详细时序表
================================================================================

+----------+--------+----------+--------------------------------+----------+
| 时间点    | 发送方  | 帧类型    | 数据内容                       | 说明      |
+----------+--------+----------+--------------------------------+----------+
| T=0ms    | 基站    | Beacon   | 周期号、时隙起始时间             | 同步时钟   |
| T=0~12ms | Tag1   | POLL     | tagId=1, 时隙=0, 里程, 线名     | 时隙0     |
| T=12~24ms| Tag2   | POLL     | tagId=2, 时隙=1, 里程, 线名     | 时隙1     |
| T=24~36ms| Tag3   | POLL     | tagId=3, 时隙=2, 里程, 线名     | 时隙2     |
| ...      | ...    | ...      | ...                            | ...       |
| T=588~600| Tag50  | POLL     | tagId=50, 时隙=49, 里程, 线名   | 时隙49    |
+----------+--------+----------+--------------------------------+----------+

================================================================================
                          4. 基站处理流程
================================================================================

基站主循环 (每1秒广播Beacon)
    |
    +-- 发送Beacon帧
    |       +-- 包含: 周期号, 时隙起始时间
    |
    +-- 等待接收 (监听所有时隙)
    |       |
    |       +-- 收到POLL -> 发送RESPONSE
    |       |       +-- RESPONSE包含: 基站ID, 时间戳t2, t3
    |       |
    |       +-- 收到FINAL -> 计算距离
    |               +-- 使用t1,t2,t3,t4,t5,t6计算
    |
    +-- 循环

================================================================================
                          5. 标签处理流程
================================================================================

标签主循环
    |
    +-- 等待Beacon (同步时钟)
    |       +-- 计算本标签时隙起始时间
    |
    +-- 等待本时隙到来
    |       +-- 判断: 当前时间是否在本时隙范围内
    |
    +-- 发送POLL
    |       +-- 包含: tagId, 时隙索引, 里程, 线名
    |
    +-- 等待RESPONSE
    |       +-- 接收基站响应, 记录时间戳
    |
    +-- 发送FINAL
    |       +-- 包含: t1(发送POLL时间), t4(接收RESPONSE时间)
    |
    +-- 等待下一周期

================================================================================
                          6. 帧数据结构
================================================================================

+-----------+--------+------------------------------------------+
| 帧类型     | 大小    | 关键字段                                  |
+-----------+--------+------------------------------------------+
| Beacon    | 32字节  | frameType, coordinatorId, totalSlots,    |
|           |        | cycleNum, txTimestamp, slotStartTime     |
+-----------+--------+------------------------------------------+
| POLL      | 30字节  | frameType, tagId, slotIndex,             |
|           |        | txTimestamp, mileage, lineName           |
+-----------+--------+------------------------------------------+
| RESPONSE  | 32字节  | frameType, tagId, anchorId,              |
|           |        | rxTimestamp, txTimestamp                 |
+-----------+--------+------------------------------------------+
| FINAL     | 36字节  | frameType, tagId, anchorId,              |
|           |        | pollTxTime, respRxTime, finalTxTime      |
+-----------+--------+------------------------------------------+

================================================================================
                          7. 时间约束
================================================================================

+----------------+--------+------------------------+
| 参数            | 值      | 说明                    |
+----------------+--------+------------------------+
| TDMA周期        | 600ms  | 50个标签 x 12ms         |
| 单时隙          | 12ms   | POLL + RESPONSE + FINAL |
| Beacon间隔      | 1000ms | 每秒广播一次             |
| 测距超时        | 10ms   | 单次测距最大等待时间      |
+----------------+--------+------------------------+

================================================================================
                          8. 距离计算公式 (DS-TWR)
================================================================================

Tround1 = t4 - t1  (标签: POLL发送 -> RESPONSE接收)
Treply1 = t3 - t2  (基站: POLL接收 -> RESPONSE发送)
Tround2 = t5 - t4  (标签: RESPONSE接收 -> FINAL发送)
Treply2 = t6 - t5  (基站: FINAL接收)

ToF = (Tround1 x Tround2 - Treply1 x Treply2) / (Tround1 + Tround2 + Treply1 + Treply2)

距离 = ToF x 光速 (299792458 m/s)

================================================================================
                          9. 设备配置
================================================================================

+----------------+----------+----------------------------------+
| 参数            | 默认值    | 说明                              |
+----------------+----------+----------------------------------+
| UWB_PAN_ID     | 0x1234   | 网络ID (所有设备相同)              |
| UWB_ANCHOR_ID  | 1        | 基站ID (每个基站唯一)              |
| UWB_TAG_ID     | 1        | 标签ID (每个标签唯一)              |
| UWB_TAG_SLOT   | 0        | 标签时隙索引                       |
| UWB_TOTAL_SLOTS| 50       | 总时隙数                          |
+----------------+----------+----------------------------------+

时隙分配规则:
  slotIndex = tagId % UWB_TOTAL_SLOTS

================================================================================
*/

#endif /* __UWB_PROTOCOL_SPEC_H */
